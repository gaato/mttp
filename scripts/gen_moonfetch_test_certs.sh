#!/usr/bin/env bash
# Writes mttp_moonfetch/src/certs_test.mbt: a test root, a certificate for
# localhost and 127.0.0.1 under it, and that certificate's key, for the local
# HTTP/2 server of gaato/mttp_moonfetch's tests. The client trusts the root
# through backend(tls=...), so no test turns certificate checking off. Valid
# from 2020 to 2040, P-256 keys, issued by OpenSSL 3.4 or later
# (-not_before/-not_after). Rerun it rather than editing the output. Each run
# makes new keys, so the gates do not compare the committed file with a fresh
# run as they do for scripts/gen_*.mbtx.
#
# Bash rather than .mbtx: it only runs openssl.
set -euo pipefail
cd "$(dirname "$0")/.."

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
start=20200101000000Z
end=20400101000000Z

openssl ecparam -name prime256v1 -genkey -noout -out "$work/root.ec"
openssl pkcs8 -topk8 -nocrypt -in "$work/root.ec" -out "$work/root.key"
openssl req -new -key "$work/root.key" -subj "/CN=mttp_moonfetch test root" \
  -out "$work/root.csr"
openssl x509 -req -in "$work/root.csr" -key "$work/root.key" \
  -not_before "$start" -not_after "$end" -sha256 \
  -extfile <(printf 'basicConstraints=critical,CA:TRUE\nkeyUsage=critical,keyCertSign\n') \
  -out "$work/root.pem"

openssl ecparam -name prime256v1 -genkey -noout -out "$work/leaf.ec"
openssl pkcs8 -topk8 -nocrypt -in "$work/leaf.ec" -out "$work/leaf.key"
openssl req -new -key "$work/leaf.key" -subj "/CN=localhost" -out "$work/leaf.csr"
openssl x509 -req -in "$work/leaf.csr" -CA "$work/root.pem" -CAkey "$work/root.key" \
  -not_before "$start" -not_after "$end" -sha256 \
  -extfile <(printf 'subjectAltName=DNS:localhost,IP:127.0.0.1\nextendedKeyUsage=serverAuth\n') \
  -out "$work/leaf.pem"

value() {
  printf '\n///|\nlet %s : String =\n' "$1"
  sed 's/^/  #|/' "$2"
}
{
  printf '// Generated by scripts/gen_moonfetch_test_certs.sh; rerun it rather than editing.\n'
  value test_root "$work/root.pem"
  value test_cert "$work/leaf.pem"
  value test_key "$work/leaf.key"
} > mttp_moonfetch/src/certs_test.mbt
echo "wrote mttp_moonfetch/src/certs_test.mbt"
